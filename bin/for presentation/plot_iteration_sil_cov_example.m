    0.89386 0.77784 2.20080 0.37208 1.17330 0.28447 0.62777]';

silthr = 0.9;
covthr = 0.5;
belowCov = covISI <= covthr;
passedSil = sil > silthr;
usedByBoth = belowCov & passedSil;

iteration_cov_table = table(iteration, sil, covISI, passedSil, belowCov, usedByBoth, ...
    'VariableNames', {'Iteration', 'SIL', 'CoV_ISI', 'PassedSIL', 'CoV_Under_0_5', 'PassedBoth'});

disp(iteration_cov_table)
fprintf('Iterations with CoV <= %.2f: %s\n', covthr, mat2str(iteration(belowCov)'))
fprintf('Iterations with SIL > %.2f and CoV <= %.2f: %s\n', ...
    silthr, covthr, mat2str(iteration(usedByBoth)'))

figure('Color', 'w', 'Position', [80 80 1350 700], ...
    'Name', 'SIL and CoV across iterations');

subplot(2, 1, 1)
plot(iteration, sil, 'o-', 'Color', [0.15 0.35 0.85], 'LineWidth', 1.2)
hold on
plot(iteration(passedSil), sil(passedSil), 'go', 'MarkerFaceColor', 'g')
yline(silthr, 'k--', sprintf(' SIL threshold %.1f', silthr), 'LineWidth', 1.2)
hold off
grid on
xlabel('FastICA iteration')
ylabel('SIL')
title('SIL across iterations')

subplot(2, 1, 2)
plot(iteration, covISI, 'o-', 'Color', [0.65 0.65 0.65], 'LineWidth', 1.2)
hold on
plot(iteration(belowCov), covISI(belowCov), 'go', 'MarkerFaceColor', 'g', ...
    'MarkerSize', 7)
plot(iteration(usedByBoth), covISI(usedByBoth), 'ro', 'MarkerSize', 10, ...
    'LineWidth', 1.5)
yline(covthr, 'k--', sprintf(' CoV threshold %.1f', covthr), 'LineWidth', 1.2)
hold off
grid on
xlabel('FastICA iteration')
ylabel('CoV of ISI')
title('CoV across iterations')
legend({'All iterations', 'CoV <= 0.5', 'SIL > 0.9 and CoV <= 0.5', 'Threshold'}, ...
    'Location', 'northeast')
