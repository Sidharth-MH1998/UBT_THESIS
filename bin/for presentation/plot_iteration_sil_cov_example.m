    0.83818 0.82962 0.98896 0.79818 0.94347 0.83504 0.83048 0.88031 0.71889 0.88894 ...
    0.85286 0.82688 0.79385 0.89453 0.79930 0.94012 0.80206]';

covISI = [ ...
    0.21547 2.09160 1.27530 1.19980 0.40403 0.20879 0.80794 0.23436 3.08220 0.99589 ...
    0.75427 0.69623 1.01680 1.08610 0.98814 1.11760 0.88360 0.41618 3.06000 1.05670 ...
