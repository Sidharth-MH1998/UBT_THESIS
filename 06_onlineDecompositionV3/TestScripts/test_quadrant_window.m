function test_quadrant_window()
%TEST_QUADRANT_WINDOW Settings live in the popup and persist into recorded cfg.
addpath(fullfile(fileparts(fileparts(mfilename('fullpath'))),'OnlineDecomposeSrc'));
app = OnlineDecompositionApp();
cleanup = onCleanup(@() delete(app));
app.Figure.Visible = 'off';
autoSave = findall(app.Figure,'Tag','autoSave');
autoSave.Value = false;
assert(isempty(findall(app.Figure,'Tag','quadrantXMU')));
click(app.Figure,'Start acquisition');
pause(0.2); drawnow;
click(app.Figure,'Quadrant');
popup = findall(groot,'Tag','OnlineAppQuadrantWindow');
x = findall(popup,'Tag','quadrantXMU');
y = findall(popup,'Tag','quadrantYMU');
smoothing = findall(popup,'Tag','quadrantSmoothingWindows');
window = findall(popup,'Tag','quadrantRateWindowSec');
history = findall(popup,'Tag','quadrantHistorySec');
axisScale = findall(popup,'Tag','quadrantAxisScale');
referenceLines = findall(popup,'Tag','quadrantShowReferenceLines');
assert(referenceLines.Value);
assert(all(strcmp(get(findall(popup,'Tag','quadrantReferenceLine'),'Visible'),'on')));
referenceLines.Value = false;
x.Value = 1;
y.Value = 4;
smoothing.Value = 6;
window.Value = 0.75;
history.Value = 5;
axisScale.Value = 2;
click(popup,'Apply settings');
cfg = app.getConfig();
assert(cfg.quadrantXMU == 1 && cfg.quadrantYMU == 4);
assert(cfg.quadrantSmoothingWindows == 6 && cfg.quadrantAxisScale == 2);
assert(~cfg.quadrantShowReferenceLines);
assert(all(strcmp(get(findall(popup,'Tag','quadrantReferenceLine'),'Visible'),'off')));
raster = findall(popup,'Tag','quadrantSelectedMURaster');
assert(isscalar(raster));
assert(isequal(cellstr(raster.YTickLabel),{'Motor unit 1';'Motor unit 2'}));
quadrant = findall(popup,'Tag','quadrantActivityAxes');
forceAxes = findall(popup,'Tag','quadrantForceAxes');
forcePanel = findall(popup,'Tag','quadrantForcePanel');
rasterPanel = findall(popup,'Tag','quadrantRasterPanel');
assert(isscalar(forceAxes) && forcePanel.Layout.Row > rasterPanel.Layout.Row);
assert(strcmp(forcePanel.BorderType,'line') && strcmp(rasterPanel.BorderType,'line'));
assert(isequal(forceAxes.YLim,[-10 80]));
forceLines = findall(forceAxes,'Tag','quadrantForceTrace');
assert(numel(forceLines) == 3);
assert(~isempty(forceLines(1).XData) && all(isfinite(forceLines(1).YData)));
assert(isscalar(findall(forceAxes,'Tag','forceMVCTarget')));
assert(strcmp(quadrant.PlotBoxAspectRatioMode,'manual'));
assert(isequal(quadrant.PlotBoxAspectRatio,[1 1 1]));
assert(contains(quadrant.XLabel.String,'G1 MU 1'));
assert(contains(quadrant.YLabel.String,'G2 MU 1'));
assert(isequal(quadrant.XLim,[0 2*cfg.quadrantReferenceRates(1)]));
assert(isequal(quadrant.YLim,[0 2*cfg.quadrantReferenceRates(4)]));
popup.Position = [20 20 1600 900];
drawnow;
assert(x.FontSize > 11);
assert(x.Parent.RowHeight{1} > 34);
assert(isequal(quadrant.PlotBoxAspectRatio,[1 1 1]));
assert(findall(popup,'Tag','quadrantWindowLayout').ColumnWidth{1} > 280);
assert(numel(findall(raster,'Type','line')) == 2);
click(app.Figure,'Start recording');
pause(0.3); drawnow;
assert(strcmp(findall(popup,'Tag','applyQuadrantSettings').Enable,'off'));
close(popup);
click(app.Figure,'Quadrant');
popup = findall(groot,'Tag','OnlineAppQuadrantWindow');
assert(strcmp(findall(popup,'Tag','quadrantXMU').Enable,'off'));
assert(findall(popup,'Tag','quadrantYMU').Value == 4);
assert(~findall(popup,'Tag','quadrantShowReferenceLines').Value);
assert(strcmp(findall(popup,'Tag','quadrantShowReferenceLines').Enable,'off'));
raster = findall(popup,'Tag','quadrantSelectedMURaster');
assert(isequal(cellstr(raster.YTickLabel),{'Motor unit 1';'Motor unit 2'}));
assert(strcmp(findall(app.Figure,'Text','Stop recording').Enable,'on'));
click(app.Figure,'Stop recording');
assert(app.LastResults.cfg.quadrantYMU == 4);
assert(app.LastResults.cfg.quadrantSmoothingWindows == 6);
assert(app.LastResults.cfg.quadrantAxisScale == 2);
assert(~app.LastResults.cfg.quadrantShowReferenceLines);
assert(strcmp(findall(popup,'Tag','applyQuadrantSettings').Enable,'on'));
click(app.Figure,'Stop acquisition');
popup.Position = [20 20 1600 900];
drawnow;
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
exportapp(popup,fullfile(root,'tmp','online_app_validation','quadrant_settings_preview.png'));
disp('Quadrant popup settings, persistence and recording-lock checks passed.');
end

function click(parent,label)
button = findall(parent,'Text',label);
assert(isscalar(button) && strcmp(button.Enable,'on'),'Unavailable button: %s',label);
callback = button.ButtonPushedFcn;
callback(button,[]);
drawnow;
end
